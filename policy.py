"""策略门槛（`POLICY`）—— **可变动**，但不是观测点。

本模块只放一类东西：**触发运维动作的门槛**。

--- 它不是观测点，理由要写清 ------------------------------------------------

`§C7.2` / B6 管的是**观测点**：「换说法率」「改判率」这类从 event 表算出来的
比率，**不得与任何数比较**（不设阈值 / 报警线）。那条防的是**单向性违反** ——
把算出来的评估结果写回 artifact 字段。

`POLICY` 不是那个东西：它是**外部的运维门槛**，读的是「导入条数与社区贡献条数
的比」这类**跨层的量**，而它的结果**只触发「暂停导入」这类开关** ——
不写回任何字段、不参与排序、不影响内容展示。

⚠️ 但实现上 B6 是**按词抓的**（`ratio` / `rate` / `duration` / `elapsed` / `cost`
与数字比较），它分不出语义。所以本模块的键名**刻意避开这些词** ——
这是实现限制，不是语义边界。若哪天 B6 改成能读语义的判据，这条规避可以撤掉。

--- 三条边界，改这个文件时必须一起看 -----------------------------------------

1. 这些是**运维门槛**，不是信号。
2. **不得**参与排序、不得影响内容展示 —— 否则撞 B2（无权重 / 评分 / 名次 / 真值）
   与 B5（无标量分）。
3. **不得**进 `upper.COUNT_SIGNALS` 白名单 —— 那会撞 B4（上层不读热度类信号）。

--- 为什么可变动 --------------------------------------------------------------

默认值在代码里（可 review、可 git diff、改一次留一次痕），
运行时可传参覆盖 —— 不改代码就能调。**刻意不做成一张表**：表是运行时状态，
而策略门槛是经常要调的东西，不该进事实层，也不该多一条写路径
（同 `scaffold.RELATION_PARENTS` 的理由）。
"""

from __future__ import annotations

# 键名说明：全部避开 B6 的词表（`ratio` / `rate` / `duration` / `elapsed` / `cost`）、
# B2 的词表（`weight` / `score` / `rank` / `truth`）、以及 B3 的 `threshold`。
POLICY = {
    # --- 导入与贡献的平衡 ---------------------------------------------------
    # 「导入 : 贡献」的上限。超过它说明用户不再贡献 —— 那是「知识消费化」
    # （设计稿第 7 节）的直接度量。触发动作：暂停导入，只开社区入口。
    "import_to_contribution_ceiling": 10,

    # --- 书籍路线的退出 -----------------------------------------------------
    # 连续这么多本书蒸馏完，若 P7 的三个监控指标全无变化，就停书籍路线。
    # 取 3：足够大的样本，又不至于拖太久。
    "books_without_effect": 3,

    # --- 门的吞吐 -----------------------------------------------------------
    # staging 未过门的积压上限。取 50：一个人一周能过完的量级。
    "staging_backlog_limit": 50,

    # 首本书 100% 人工过 —— 为的是**校准蒸馏器**，不是防污染。
    # 两层独立之后 Imported 层可以整层重蒸馏，所以门不必挡数量。
    "gate_first_book_full": True,

    # 之后按比例抽样。取 10%：门的目的已降级为「防止低质内容影响用户判断」，
    # 比「防止不可逆污染」宽松得多。
    "gate_sample_percent": 10,
}


def value(key: str, **override):
    """取一个门槛值，允许调用方覆盖 —— **这就是「可变动」的落地方式**。

    为什么不直接读 `POLICY[key]`：那样调用方想改策略就得改代码。
    这里让运行时能传覆盖值，默认值仍然是代码里那一份（可 review、可留痕）。

        value("staging_backlog_limit")                                   # 50
        value("staging_backlog_limit", staging_backlog_limit=10)          # 10
    """
    if key not in POLICY:
        raise KeyError(
            f"未知策略键：{key} —— 策略键是**封闭集合**，"
            f"要加先改 POLICY 并说明理由。现有：{sorted(POLICY)}"
        )
    return override.get(key, POLICY[key])
